import fs from 'node:fs';
import assert from 'node:assert/strict';
const base = new URL('./',import.meta.url);
const three = new URL('lib/three/three.module.js',base).href;
const dataURL = s => 'data:text/javascript;base64,'+Buffer.from(s).toString('base64');
const orbit = dataURL(fs.readFileSync(new URL('lib/three/OrbitControls.js',base),'utf8').replace("from 'three'",`from '${three}'`));
const source=fs.readFileSync(new URL('js/viewer.js',base),'utf8').replace("from 'three'",`from '${three}'`).replace("from 'three/addons/controls/OrbitControls.js'",`from '${orbit}'`);
const {MuJoCoViewer}=await import(dataURL(source));
const {Vector3}=await import(three);
const viewer=new MuJoCoViewer({});
viewer._ready=true;
viewer.data={xpos:new Float64Array([0,0,0,1,2,3]),xmat:new Float64Array([...Array(9).fill(0),1,0,0,0,1,0,0,0,1]),xipos:new Float64Array([0,0,0,1,2,3]),xfrc_applied:new Float64Array(12)};
viewer._drag={active:true,bodyId:1,localAnchor:new Vector3(1,0,0),anchor:new Vector3(),current:new Vector3(2,2,2)};
viewer._applyDragForce();
assert.deepEqual(Array.from(viewer.data.xfrc_applied.slice(6)),[0,0,-50,-0,50,0]);
viewer.controls={enabled:false};viewer._dragArrow={visible:true};viewer._dragSphere={visible:true};
viewer.clearDragForce();
assert.equal(viewer._drag.active,false);assert.equal(viewer.controls.enabled,true);
assert.ok(viewer.data.xfrc_applied.every(x=>x===0));assert.equal(viewer._dragArrow.visible,false);
console.log('PASS: world force, lever-arm torque, body-local anchor, and reset clears force/drag.');
