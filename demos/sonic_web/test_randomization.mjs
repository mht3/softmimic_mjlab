import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {DomainRandomizer,objectNames} from './js/randomization.js';
globalThis.navigator={hardwareConcurrency:1};
const {default:load}=await import('./lib/mujoco_wasm.js');
const mj=await load();
const assets=path.resolve(process.argv[2]||'demos/sonic_web/assets');
mj.FS.mkdir('/working');mj.FS.mkdir('/working/meshes');
mj.FS.writeFile('/working/scene.xml',fs.readFileSync(path.join(assets,'robot/scene.xml')));
for(const name of fs.readdirSync(path.join(assets,'robot/meshes')))mj.FS.writeFile('/working/meshes/'+name,fs.readFileSync(path.join(assets,'robot/meshes',name)));
const model=mj.MjModel.mj_loadXML('/working/scene.xml'),data=new mj.MjData(model);
const dr=new DomainRandomizer(model,()=>mj.mj_setConst(model,data));
const options={seed:42,mass:true,actuators:true,limits:true,friction:true,trainingContacts:true};
const values=dr.apply(options),snapshot=Object.fromEntries(Object.keys(dr.base).map(k=>[k,Array.from(model[k])]));
assert.ok(values.foot_friction>=.5&&values.foot_friction<=2);
const torso=objectNames(model,'body').indexOf('torso_link');
assert.equal(model.body_mass[torso],dr.base.body_mass[torso]+values.payload_kg);
for(let j=0;j<3;j++)assert.ok(Math.abs(model.body_inertia[3*torso+j]/dr.base.body_inertia[3*torso+j]-model.body_mass[torso]/dr.base.body_mass[torso])<1e-12);
for(let i=6;i<model.nv;i++)assert.ok(model.dof_armature[i]-dr.base.dof_armature[i]>=.01&&model.dof_armature[i]-dr.base.dof_armature[i]<=.1);
dr.apply({...options,seed:43});assert.notDeepEqual(Array.from(model.body_mass),snapshot.body_mass);
dr.apply(options);for(const k of Object.keys(dr.base))assert.deepEqual(Array.from(model[k]),snapshot[k],k+' reset must not accumulate');
dr.apply();for(const k of Object.keys(dr.base))assert.deepEqual(Array.from(model[k]),Array.from(dr.base[k]),k+' nominal restore');
assert.throws(()=>dr.apply({seed:NaN}),/Seed/);
if(process.argv[3])fs.writeFileSync(process.argv[3],JSON.stringify(snapshot));
console.log('PASS: actual WASM mass/inertia, bounds, deterministic seeds, no accumulation, nominal restoration');process.exit(0);
